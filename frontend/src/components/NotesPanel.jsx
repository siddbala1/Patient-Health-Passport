import { useState, useEffect } from 'react';
import { fetchNotes } from '../api';

const STATUS_MESSAGES = {
  not_configured: 'Plain-language explanations are not set up yet.',
  unavailable: "We couldn't prepare an explanation right now. Please try again later.",
  needs_review:
    "This explanation didn't pass our accuracy check, so it is hidden. Your care team can go over this note with you.",
};

function formatDate(iso) {
  if (!iso) return '';
  const d = new Date(`${iso}T00:00:00`);
  return Number.isNaN(d.getTime())
    ? iso
    : d.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });
}

function NoteCard({ note }) {
  return (
    <article className="note-card">
      <h4 className="note-card__title">
        {note.title}
        {note.date && <span className="note-card__date">{formatDate(note.date)}</span>}
      </h4>

      {note.status !== 'ready' ? (
        <p className="note-card__status">{STATUS_MESSAGES[note.status]}</p>
      ) : (
        <>
          <p className="note-card__summary">{note.summary}</p>

          {note.terms.length > 0 && (
            <>
              <h5 className="note-card__heading">What the terms mean</h5>
              <dl className="note-card__terms">
                {note.terms.map((t, i) => (
                  <div key={i}>
                    <dt>{t.term}</dt>
                    <dd>{t.meaning}</dd>
                  </div>
                ))}
              </dl>
            </>
          )}

          {note.next_steps.length > 0 && (
            <>
              <h5 className="note-card__heading">Next steps in your plan</h5>
              <ul className="note-card__steps">
                {note.next_steps.map((s, i) => (
                  <li key={i}>{s}</li>
                ))}
              </ul>
            </>
          )}
        </>
      )}
    </article>
  );
}

// Mounted only while its tab is open (Tabs renders just the active panel), so
// the first visit is what triggers a note's explanation to be generated.
export default function NotesPanel({ sessionId }) {
  const [notes, setNotes] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => {
    if (!sessionId) return;
    let cancelled = false;
    fetchNotes(sessionId)
      .then((n) => !cancelled && setNotes(n))
      .catch((err) => !cancelled && setError(err.message));
    return () => {
      cancelled = true;
    };
  }, [sessionId]);

  if (error) return <p className="empty-message">Couldn't load visit notes: {error}</p>;
  if (!notes) {
    return <p className="empty-message">Preparing plain-language explanations of your visit notes…</p>;
  }
  if (notes.length === 0) return <p className="empty-message">No visit notes on record.</p>;

  return (
    <div className="notes-panel">
      {notes.map((note) => (
        <NoteCard key={note.id} note={note} />
      ))}
      <p className="notes-panel__disclaimer">
        These explanations are generated by AI to help you understand your visit notes. They are not
        medical advice and can contain mistakes. Ask your care team if anything is unclear.
      </p>
    </div>
  );
}
